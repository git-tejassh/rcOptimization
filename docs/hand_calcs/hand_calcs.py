"""Independent worked IS 456:2000 examples (closed formulas only; does NOT import rcopt).

Run ``python docs/hand_calcs/hand_calcs.py`` to regenerate ``beam_example.md`` and ``column_example.md``.
``tests/test_hand_calcs.py`` compares the rcopt code against ``beam()`` and ``column()`` below.
The owner should re-derive at least one beam and one column by hand from these intermediate values.
Steel curve: SP 16 total-strain table typed in directly (not built from the config), concrete block integrated with
``scipy.integrate.quad``.
"""
from __future__ import annotations

import math
from pathlib import Path

from scipy.integrate import quad

HERE = Path(__file__).parent

# SP 16 / IS 456 Fig. 23 design curve, total strains for 0.8 .. 1.0 fyd (typed, Fe500)
FE500_STRAIN = [0.0, 0.00174, 0.00195, 0.00226, 0.00277, 0.00312, 0.00417]
FE500_FRAC = [0.0, 0.80, 0.85, 0.90, 0.95, 0.975, 1.00]


def fs_fe500(eps: float) -> float:
    fyd = 0.87 * 500.0
    e = abs(eps)
    for k in range(1, len(FE500_STRAIN)):
        if e <= FE500_STRAIN[k]:
            f0, f1 = FE500_FRAC[k - 1], FE500_FRAC[k]
            e0, e1 = FE500_STRAIN[k - 1], FE500_STRAIN[k]
            return math.copysign(fyd * (f0 + (f1 - f0) * (e - e0) / (e1 - e0)), eps)
    return math.copysign(fyd, eps)


def beam() -> dict:
    """Singly reinforced beam: 300 x 500, M25, Fe500, cover 30, 8 mm stirrups, 4-20 bottom, flexure + shear."""
    b, D, fck, fy, cover, st, bar, n = 300.0, 500.0, 25.0, 500.0, 30.0, 8.0, 20.0, 4
    d = D - cover - st - bar / 2                               # 452
    Ast = n * math.pi / 4 * bar**2                              # 1256.6
    xu = 0.87 * fy * Ast / (0.36 * fck * b)
    k_lim = 0.46
    xu_max = k_lim * d
    Mu = 0.87 * fy * Ast * d * (1 - Ast * fy / (b * d * fck))   # Annex G-1.1 (b)
    Mu_lim = 0.36 * fck * b * xu_max * (d - 0.42 * xu_max)
    pt = 100 * Ast / (b * d)
    # shear: Table 19 for M25: pt 0.75 -> 0.57, 1.00 -> 0.64 (interpolated); Table 20 tau_c,max = 3.1
    tau_c = 0.57 + (0.64 - 0.57) * (pt - 0.75) / 0.25
    Vu = 150e3
    tau_v = Vu / (b * d)
    Asv = 2 * math.pi / 4 * 8.0**2
    Vus = Vu - tau_c * b * d
    sv_strength = 0.87 * min(fy, 415) * Asv * d / Vus
    return {"d": d, "Ast": Ast, "xu": xu, "xu_max": xu_max, "Mu_kNm": Mu / 1e6, "Mu_lim_kNm": Mu_lim / 1e6,
            "pt": pt, "tau_c": tau_c, "tau_v": tau_v, "Vus_kN": Vus / 1e3, "sv_strength_mm": sv_strength,
            "inputs": dict(b=b, D=D, fck=fck, fy=fy, cover=cover, st=st, bar=bar, n=n, Vu_kN=Vu / 1e3)}


def column(xu_over_D: float = 0.6) -> dict:
    """Column 450 x 450, M30, Fe500, 8-20 bars (3 top, 2+... see rows), cover 40, tie 8: P-M point at xu = 0.6 D."""
    b = D = 450.0
    fck = 30.0
    cover, tie, bar = 40.0, 8.0, 20.0
    A1 = math.pi / 4 * bar**2
    c = cover + tie + bar / 2                                   # 58
    rows = [(c, 3 * A1), (D / 2, 2 * A1), (D - c, 3 * A1)]      # 8 bars: 3 top, 2 sides, 3 bottom
    Asc = 8 * A1
    xu = xu_over_D * D

    def eps(y: float) -> float:
        return 0.0035 * (xu - y) / xu                           # xu <= D

    def sig_c(e: float) -> float:
        if e <= 0:
            return 0.0
        r = min(e, 0.002) / 0.002
        return 0.446 * fck * (2 * r - r * r)

    Cc = quad(lambda y: sig_c(eps(y)) * b, 0, xu, limit=200)[0]
    Mc = quad(lambda y: sig_c(eps(y)) * b * (D / 2 - y), 0, xu, limit=200)[0]
    P, M = Cc, Mc
    detail = []
    for y, A in rows:
        e = eps(y)
        f = fs_fe500(e) - sig_c(e)
        detail.append({"y_mm": y, "strain": e, "stress_net_MPa": f, "force_kN": f * A / 1e3})
        P += f * A
        M += f * A * (D / 2 - y)
    Puz = 0.45 * fck * (b * D - Asc) + 0.75 * 500.0 * Asc
    return {"xu": xu, "P_kN": P / 1e3, "M_kNm": M / 1e6, "Cc_kN": Cc / 1e3, "Puz_kN": Puz / 1e3, "Asc": Asc,
            "rows": detail, "inputs": dict(b=b, D=D, fck=fck, fy=500, cover=cover, tie=tie, bar=bar, n=8)}


def _md_beam(r: dict) -> str:
    i = r["inputs"]
    return f"""# Hand calculation: beam (IS 456:2000)

Section {i['b']:.0f} x {i['D']:.0f} mm, M{i['fck']:.0f}, Fe{i['fy']:.0f}, clear cover {i['cover']:.0f} mm, 8 mm stirrups,
{i['n']} - {i['bar']:.0f} mm bars at the bottom, Vu = {i['Vu_kN']:.0f} kN. Generated by `hand_calcs.py` (closed formulas only).

| Step | Formula | Value |
|---|---|---|
| Effective depth | d = D - cover - stirrup - bar/2 | {r['d']:.1f} mm |
| Tension steel | Ast = n pi/4 phi^2 | {r['Ast']:.1f} mm2 |
| Neutral axis | xu = 0.87 fy Ast / (0.36 fck b) (cl. G-1.1) | {r['xu']:.1f} mm |
| Limit | xu,max = 0.46 d (Fe500, cl. 38.1) | {r['xu_max']:.1f} mm  (xu < xu,max: under-reinforced) |
| Moment capacity | Mu = 0.87 fy Ast d (1 - Ast fy / (b d fck)) (G-1.1 b) | {r['Mu_kNm']:.2f} kN.m |
| Limiting moment | Mu,lim = 0.36 fck b xu,max (d - 0.42 xu,max) | {r['Mu_lim_kNm']:.2f} kN.m |
| Steel percentage | pt = 100 Ast/(b d) | {r['pt']:.3f} % |
| tau_c (Table 19, M25, interpolated) | 0.57 + 0.07 (pt - 0.75)/0.25 | {r['tau_c']:.3f} N/mm2 |
| tau_v | Vu/(b d) | {r['tau_v']:.3f} N/mm2 (< tau_c,max = 3.1) |
| Vus | Vu - tau_c b d | {r['Vus_kN']:.1f} kN |
| Stirrup spacing (2-legged 8 mm, fy capped at 415) | sv = 0.87 fy Asv d / Vus (cl. 40.4) | {r['sv_strength_mm']:.0f} mm |

Table 19 / Table 20 values are transcribed from memory: **verify against your copy of IS 456 (docs/ASSUMPTIONS.md A1-A2)**.
"""


def _md_col(r: dict) -> str:
    i = r["inputs"]
    rows = "\n".join(f"| {d['y_mm']:.0f} | {d['strain']:.5f} | {d['stress_net_MPa']:.1f} | {d['force_kN']:.1f} |" for d in r["rows"])
    return f"""# Hand calculation: column P-M point (IS 456:2000)

Section {i['b']:.0f} x {i['D']:.0f} mm, M{i['fck']:.0f}, Fe500, clear cover {i['cover']:.0f} mm, {i['tie']:.0f} mm ties, 8 - {i['bar']:.0f} mm
bars (3 top, 2 side, 3 bottom). Strain profile: eps_cu = 0.0035 at the compression face, neutral axis xu = 0.6 D = {r['xu']:.0f} mm.
Concrete: parabola-rectangle block 0.446 fck (integrated with `quad`); steel: SP 16 total-strain table (typed in), force net of displaced concrete.

| Bar row y from compression face (mm) | strain | net stress (MPa) | force (kN) |
|---|---|---|---|
{rows}

Concrete force Cc = {r['Cc_kN']:.1f} kN.  **Pu = {r['P_kN']:.1f} kN, Mu (about the centroid) = {r['M_kNm']:.2f} kN.m.**
Axial capacity (cl. 39.6) Puz = 0.45 fck (Ac - Asc) + 0.75 fy Asc = {r['Puz_kN']:.1f} kN  (Asc = {r['Asc']:.1f} mm2).
"""


if __name__ == "__main__":
    (HERE / "beam_example.md").write_text(_md_beam(beam()), encoding="utf-8")
    (HERE / "column_example.md").write_text(_md_col(column()), encoding="utf-8")
    print("written")
